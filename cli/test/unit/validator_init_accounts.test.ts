function harness(
  options: {
    network?: 'mainnet' | 'testnet'
    answers?: string[]
    badReadback?: boolean
    failCreate?: boolean
    context?: NonNullable<Parameters<typeof setupDeps>[1]>['context']
  } = {},
) {
  const network = options.network ?? 'testnet'
  const terminal = scriptedTty(
    options.answers ??
      ['1', ...(network === 'mainnet' ? ['Example vault'] : [])],
  )
  const made: Uint8Array[] = []
  let created = false
  const op = scriptedOp((call) => {
    const [a, b] = call.args
    if (a === 'vault' && b === 'list') {
      return {
        success: true,
        stdout: JSON.stringify([{ id: VAULT, name: 'Example vault' }]),
      }
    }
    if (a === 'item' && b === 'list') {
      return {
        success: true,
        stdout: JSON.stringify(
          created
            ? [{ id: ITEM, title: `SLV ${network} example identity` }]
            : [],
        ),
      }
    }
    if (a === 'item' && b === 'create') {
      if (options.failCreate) {
        return { success: false, stderr: 'Synthetic create failure' }
      }
      const body = JSON.parse(new TextDecoder().decode(call.stdin!))
      assertEquals(body.fields[0].value, KEY_A.canonical)
      assertEquals(body.fields[1].value, KEY_A.pubkey)
      created = true
      return { success: true }
    }
    if (a === 'read') {
      return {
        success: true,
        stdout: call.args[2].endsWith('/pubkey')
          ? KEY_A.pubkey
          : options.badReadback
          ? KEY_B.canonical
          : KEY_A.canonical,
      }
    }
    throw new Error('Unexpected op request')
  }, { recordStdin: true, keepStdin: true })
  const deps = {
    setup: setupDeps(op.op, {
      readConfig: () =>
        Promise.resolve({
          networks: { [network]: { vaultId: VAULT, tokenFile: null } },
          identityAgent: null,
        }),
      ...(options.context ? { context: options.context } : {}),
    }),
    tty: terminal.tty,
    generate: () => {
      const bytes = KEY_A.keypair.slice()
      made.push(bytes)
      return Promise.resolve(bytes)
    },
    writeVault: () => {
      throw new Error('Already configured vault must not be written')
    },
    onchain: {
      fetch: () => {
        throw new Error('Fresh sync-only setup must not send any RPC request')
      },
    },
  }
  return { deps, op, terminal, made }
}

Deno.test('fresh testnet and human-only mainnet identities go through memory, vault verification and public-only inventory metadata', async () => {
  for (const network of ['testnet', 'mainnet'] as const) {
    const h = harness({ network })
    const accounts = await prepareValidatorInitAccounts(
      network,
      'example',
      h.deps,
    )
    assertEquals(accounts, {
      identity_account: KEY_A.pubkey,
      identity_ref: refOf(),
      vote_account: '',
      authority_account: '',
      no_voting: true,
    })
    assertEquals(h.made.length, 1)
    assert(h.made[0].every((byte) => byte === 0))
    assert(h.op.calls.every((call) => call.env.OP_CACHE === 'false'))
    const create = h.op.calls.find((call) => call.args[1] === 'create')!
    assertEquals(create.stdout, 'null')
    assert(create.stdinRef!.every((byte) => byte === 0))
    const visible = JSON.stringify({
      accounts,
      prompts: h.terminal.asked,
      output: h.terminal.said,
      args: h.op.calls.map((call) => [call.args, call.env]),
    })
    assertFalse(holdsKey(visible, KEY_A))
    assertFalse(holdsKey(visible, KEY_B))
    if (network === 'mainnet') {
      assert(
        h.terminal.asked.some((prompt) => prompt.includes('name of the vault')),
      )
    }
  }
})

Deno.test('a vault failure or mismatched readback returns no usable metadata and wipes generated bytes', async () => {
  for (const failure of [{ failCreate: true }, { badReadback: true }]) {
    const h = harness(failure)
    const error = await assertRejects(() =>
      prepareValidatorInitAccounts('testnet', 'example', h.deps)
    )
    assertFalse(holdsKey(String(error), KEY_A))
    assertFalse(holdsKey(String(error), KEY_B))
    assert(h.made.every((bytes) => bytes.every((byte) => byte === 0)))
    assertFalse(
      h.terminal.said.some((line) => line.includes('identity verified')),
    )
  }
})

