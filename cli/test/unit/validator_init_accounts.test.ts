Deno.test('inventory commits the complete public-only bootstrap host atomically and refuses replacement', async () => {
  const dir = await Deno.makeTempDir({ prefix: 'slv-init-inventory-' })
  try {
    const path = `${dir}/inventory.yml`
    await Deno.writeTextFile(
      path,
      'unrelated: kept\ntestnet_validators:\n  vars:\n    kept: true\n  hosts:\n    old:\n      identity_account: ExistingPublicIdentity\n',
    )
    const h = harness()
    const accounts = await prepareValidatorInitAccounts(
      'testnet',
      'example',
      h.deps,
    )
    await assertNewValidatorHost('testnet', 'example', path)
    await saveValidatorInitHost('testnet', 'example', accounts, path)
    const raw = await Deno.readTextFile(path)
    const data = parse(raw) as {
      unrelated: string
      testnet_validators: { vars: unknown; hosts: Record<string, unknown> }
    }
    assertEquals(data.unrelated, 'kept')
    assertEquals(data.testnet_validators.vars, { kept: true })
    assertEquals(data.testnet_validators.hosts.example, accounts)
    assertEquals(data.testnet_validators.hosts.old, {
      identity_account: 'ExistingPublicIdentity',
    })
    assertFalse(holdsKey(raw, KEY_A))
    await assertRejects(() =>
      saveValidatorInitHost('testnet', 'example', {
        identity_account: 'replacement',
      }, path)
    )
    assertEquals(await Deno.readTextFile(path), raw)
    await assertRejects(() => assertNewValidatorHost('testnet', 'old', path))
    assertEquals([...Deno.readDirSync(dir)].map((entry) => entry.name), [
      'inventory.yml',
    ])
  } finally {
    await Deno.remove(dir, { recursive: true })
  }
})

