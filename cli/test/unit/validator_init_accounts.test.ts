Deno.test('linked inventory keeps its symlink and updates the real target; dangling links fail before setup', async () => {
  const dir = await Deno.makeTempDir({ prefix: 'slv-linked-init-' })
  try {
    const target = `${dir}/shared.yml`
    const link = `${dir}/inventory.yml`
    await Deno.writeTextFile(
      target,
      'testnet_validators:\n  hosts:\n    existing: {identity_account: ExamplePublicKey}\n',
    )
    await Deno.symlink('shared.yml', link)
    await assertNewValidatorHost('testnet', 'new', link)
    await saveValidatorInitHost('testnet', 'new', {
      no_voting: true,
      identity_ref: refOf(),
    }, link)
    assert((await Deno.lstat(link)).isSymlink)
    assertEquals(await Deno.readLink(link), 'shared.yml')
    const contents = await Deno.readTextFile(target)
    assertStringIncludes(contents, 'existing:')
    assertStringIncludes(contents, 'no_voting: true')
    assertEquals(await Deno.readTextFile(link), contents)
    await Deno.symlink('missing.yml', `${dir}/dangling.yml`)
    await assertRejects(
      () => assertNewValidatorHost('testnet', 'new', `${dir}/dangling.yml`),
      Error,
      'symlink has no target',
    )
    await assertRejects(
      () => saveValidatorInitHost('testnet', 'new', {}, `${dir}/dangling.yml`),
      Error,
      'symlink has no target',
    )
    assert((await Deno.lstat(`${dir}/dangling.yml`)).isSymlink)
  } finally {
    await Deno.remove(dir, { recursive: true })
  }
})

